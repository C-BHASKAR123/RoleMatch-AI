"""Build ``app.py`` -- a single self-contained RoleMatch AI bundle.

The generated file embeds the whole backend + frontend as a compressed,
base64-encoded archive and extracts itself at startup. Run this any time the
source changes:

    python make_single_file.py
"""

import base64
import io
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "app.py"
TARGETS = ("backend", "frontend")

TEMPLATE = '''"""RoleMatch AI \u2014 single-file bundle.

Everything the app needs (backend + frontend) is embedded in this one file as a
compressed, base64-encoded archive. On startup it extracts itself to a temporary
directory and exposes the FastAPI app as ``app``.

Run it with:

    uvicorn app:app --host 0.0.0.0 --port $PORT

Only ``requirements.txt`` is needed alongside it. Generated by
``make_single_file.py`` \u2014 do not edit by hand.
"""

import base64
import io
import os
import sys
import tempfile
import zipfile
from pathlib import Path

_PACKAGE_B64 = "__PACKAGE_B64__"


def _bootstrap() -> Path:
    """Extract the embedded archive and put it on ``sys.path``."""
    target = Path(tempfile.mkdtemp(prefix="rolematch_"))
    raw = base64.b64decode(_PACKAGE_B64)
    with zipfile.ZipFile(io.BytesIO(raw)) as zf:
        zf.extractall(target)
    if str(target) not in sys.path:
        sys.path.insert(0, str(target))
    return target


_PACKAGE_DIR = _bootstrap()

from backend.main import app  # noqa: E402

__all__ = ["app"]


if __name__ == "__main__":
    import uvicorn

    port = int(os.environ.get("PORT", "8000"))
    print(f"RoleMatch AI bundle running on http://0.0.0.0:{port}")
    uvicorn.run(app, host="0.0.0.0", port=port)
'''


def build_archive() -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for folder in TARGETS:
            base = ROOT / folder
            for path in sorted(base.rglob("*")):
                if path.is_dir() or "__pycache__" in path.parts:
                    continue
                if path.suffix in {".pyc", ".pyo"}:
                    continue
                zf.write(path, path.relative_to(ROOT).as_posix())
    return buf.getvalue()


def main() -> None:
    raw = build_archive()
    encoded = base64.b64encode(raw).decode("ascii")
    source = TEMPLATE.replace("__PACKAGE_B64__", encoded)
    OUTPUT.write_text(source, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    print(f"  bundle size : {len(raw) / 1024:.1f} KB")
    print(f"  app.py size : {OUTPUT.stat().st_size / 1024:.1f} KB")


if __name__ == "__main__":
    main()
